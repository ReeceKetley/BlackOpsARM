"""Generate fixture-only numeric metadata from independently verified originals."""
import argparse
import json
from pathlib import Path
from bootstrap_default_oracle import reference


def generate(game_root, output):
    lines = ['// Generated by generate_bootstrap_default_expected.py; no retail payload bytes.',
             '#pragma once', '#include <cstdint>', 'namespace bootstrap_expected {',
             'struct Record { const char* kind; std::uint32_t source_start, source_end, disk_start, native64_start, disk_bytes, native64_bytes, block, adler32; };',
             'struct Fixup { const char* kind; std::uint32_t tag, disk_target, native64_target, target_source; };',
             'struct Argument { std::uint32_t source, type, dest, value; };',
             'struct Graph { const Record* records; std::uint32_t record_count; const Fixup* fixups; std::uint32_t fixup_count; const Argument* arguments; std::uint32_t argument_count; std::uint32_t source_end, disk_end, native64_end, null_techniques, asset_count, string_count, decoded_bytes, decoded_adler32, header_adler32; const char* prefix_sha256; };']
    for label, name in [('mp', 'code_post_gfx_mp'), ('sp', 'code_post_gfx')]:
        g = reference(Path(game_root) / 'zone/common' / (name + '.ff'))
        lines.append('inline constexpr Record ' + label + '_records[] = {')
        for r in g['records']:
            fields = [r[k] for k in ['source_start', 'source_end', 'disk_start', 'native64_start', 'disk_bytes', 'native64_bytes', 'block', 'adler32']]
            lines.append(' {' + json.dumps(r['kind']) + ', ' + ', '.join(str(v) + 'u' for v in fields) + '},')
        lines.append('};')
        lines.append('inline constexpr Fixup ' + label + '_fixups[] = {')
        for r in g['fixups']:
            lines.append(' {' + json.dumps(r['kind']) + ', ' + ', '.join(str(r[k]) + 'u' for k in ['tag', 'disk_target', 'native64_target', 'target_source']) + '},')
        lines.append('};')
        arguments = []
        for r in g['records']:
            for i, a in enumerate(r.get('fields', [])):
                arguments.append([r['source_start'] + i * 8, a['type'], a['dest'], a['value']])
        lines.append('inline constexpr Argument ' + label + '_arguments[] = {')
        lines += [' {' + ', '.join(str(v) + 'u' for v in a) + '},' for a in arguments]
        lines.append('};')
        header = next(r for r in g['records'] if r['kind'] == 'technique_set')
        fields = [g[k] for k in ['source_end', 'block4_disk_end', 'block4_native64_end', 'null_techniques', 'asset_count', 'string_count', 'decoded_bytes', 'decoded_adler32']] + [header['adler32']]
        lines.append('inline constexpr Graph ' + label + ' = {' + label + '_records, ' + str(len(g['records'])) + 'u, ' + label + '_fixups, ' + str(len(g['fixups'])) + 'u, ' + label + '_arguments, ' + str(len(arguments)) + 'u, ' + ', '.join(str(v) + 'u' for v in fields) + ', ' + json.dumps(g['prefix_sha256']) + '};')
    lines.append('}')
    Path(output).write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')


if __name__ == '__main__':
    p = argparse.ArgumentParser()
    p.add_argument('--game-root', type=Path, required=True)
    p.add_argument('--output', type=Path, required=True)
    args = p.parse_args()
    generate(args.game_root, args.output)
